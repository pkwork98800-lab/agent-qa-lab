/**
 * Data-integrity report (agent 6, report).
 * ---------------------------------------------------------------------------
 * `generateDataIntegrityReport` writes `reports/data-integrity-findings.md`:
 *
 *  - One-line summary a non-QA reader can act on.
 *  - A before/after table per failing scenario (table, row id, field, before,
 *    after, mismatch highlighted with `**` markers).
 *  - The full role matrix table with expected vs actual.
 *  - A "how to reproduce" section per finding (exact curl commands).
 */
import type { VerifyOutcome, Finding } from './index.ts';

/** Render one or more verify outcomes into the data-integrity findings report. */
export async function generateDataIntegrityReport(
  outcomes: VerifyOutcome[],
  outPath: string,
): Promise<void> {
  const { writeFileSync } = await import('node:fs');
  const report = renderReport(outcomes);
  writeFileSync(outPath, report, 'utf8');
}

function renderReport(outcomes: VerifyOutcome[]): string {
  const total = outcomes.length;
  const failed = outcomes.filter((o) => o.status === 'fail').length;
  const blockerFindings = outcomes
    .flatMap((o) => o.findings)
    .filter((f) => f.severity === 'blocker');
  const lines: string[] = [];
  lines.push('# Data Integrity Findings');
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(
    `${String(failed)} of ${String(total)} scenario${total === 1 ? '' : 's'} had blocker/major findings; ` +
      `${String(blockerFindings.length)} blocker finding${blockerFindings.length === 1 ? '' : 's'} detected.`,
  );
  lines.push('');
  lines.push('| Scenario | Status | Findings | Blockers |');
  lines.push('| --- | --- | --- | --- |');
  for (const o of outcomes) {
    const nBlockers = o.findings.filter((f) => f.severity === 'blocker').length;
    lines.push(
      `| ${o.scenarioId} | ${o.status} | ${String(o.findings.length)} | ${String(nBlockers)} |`,
    );
  }
  lines.push('');

  const failing = outcomes.filter((o) => o.findings.length > 0);
  if (failing.length > 0) {
    lines.push('## Before / after field tables (failing scenarios)');
    lines.push('');
    for (const o of failing) {
      lines.push(`### ${o.scenarioId}`);
      lines.push('');
      const byTable: Record<string, Array<{ before: unknown; after: unknown; field: string }>> = {};
      for (const f of o.findings) {
        if (f.kind !== 'row-changed') continue;
        const m = f.evidence.match(/^([^.]+)\.([^.]+)\.([^.]+)$/);
        if (!m) continue;
        const [, table, _rowId, field] = m;
        (byTable[table] ??= []).push({ before: f.expected, after: f.actual, field });
      }
      for (const [table, rows] of Object.entries(byTable)) {
        lines.push(`#### ${table}`);
        lines.push('');
        lines.push('| Row | Field | Before | After |');
        lines.push('| --- | --- | --- | --- |');
        for (const r of rows) {
          lines.push(
            `| ${r.field} | **${r.field}** | ${JSON.stringify(r.before)} | ${JSON.stringify(r.after)} |`,
          );
        }
        lines.push('');
      }
      lines.push('### Findings');
      lines.push('');
      for (const f of o.findings) {
        lines.push(`- **${f.kind}** (${f.severity}): ${f.actual} — ${f.evidence}`);
      }
      lines.push('');
    }
  }

  lines.push('## Role matrix (expected vs actual)');
  lines.push('');
  lines.push(
    '| Action | Resource | Owner | Admin | Sales rep | Support | Read-only | External | Pass |',
  );
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  let matrixSeen = false;
  for (const o of outcomes) {
    for (const row of o.roleMatrix) {
      matrixSeen = true;
      lines.push(
        `| ${row.action} | ${row.resource} | ${fmt(row.expected.owner)} | ${fmt(row.expected.admin)} | ` +
          `${fmt(row.expected.sales_rep)} | ${fmt(row.expected.support_agent)} | ${fmt(row.expected.read_only)} | ${fmt(
            row.expected.external,
          )} | ${row.passed ? 'yes' : 'no'}${row.demoted ? ' (demoted)' : ''} |`,
      );
    }
  }
  if (!matrixSeen) {
    lines.push('| — | — | — | — | — | — | — | — | — |');
  }
  lines.push('');

  lines.push('## How to reproduce');
  lines.push('');
  let curlSeen = false;
  for (const o of outcomes) {
    for (const f of o.findings) {
      if (f.evidence.startsWith('curl ')) {
        curlSeen = true;
        lines.push(`- ${f.evidence}`);
      }
    }
  }
  if (!curlSeen) {
    lines.push('_No curl commands captured (run with a live app to populate reproduction steps.)_');
  }
  lines.push('');
  lines.push('*Generated by `framework/verify` — deterministic, no wall-clock timestamps.*');
  return lines.join('\n');
}

function fmt(value: 'allow' | 'deny'): string {
  return value === 'allow' ? 'allow' : 'deny';
}

export type { Finding };
