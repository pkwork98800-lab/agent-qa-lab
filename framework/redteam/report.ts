/**
 * `generateRedTeamReport` → `reports/red-team-report.md`.
 * ---------------------------------------------------------------------------
 * Renders a red-team safety report from a set of `RunResult[]` and the probe
 * catalogue. One-line summary, severity table (probe id, category, severity,
 * pass/fail, evidence, repro, fix recommendation), a 60-second blocker repro
 * section, and a hardening section. No wall-clock timestamps: the same input
 * regenerates byte-identically.
 */
import type { RunResult, Severity, ScenarioCategory } from '../../src/contracts/types.ts';
import { parseScenario } from '../../scenarios/_schema.ts';
import { PROBES, type Probe } from './probes.ts';
import { severityForCategory, severityRank } from './severity.ts';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

function repoRoot(): string {
  return join(dirname(import.meta.url), '..', '..', '..');
}

function scenarioDir(probesPath?: string): string {
  if (probesPath) return probesPath;
  return join(repoRoot(), 'scenarios', 'redteam');
}

/** Map scenarioId → probeId by parsing every scenario file in the redteam dir. */
function loadProbeIds(scenarioDirPath: string): Map<string, string> {
  const map = new Map<string, string>();
  let files: string[];
  try {
    files = readdirSync(scenarioDirPath);
  } catch {
    return map;
  }
  for (const name of files.sort()) {
    if (!name.endsWith('.json')) continue;
    try {
      const raw: unknown = JSON.parse(readFileSync(join(scenarioDirPath, name), 'utf8'));
      const s = parseScenario(raw, name);
      if (s.redteam) map.set(s.id, s.redteam.probeId);
    } catch {
      // Ignore unparseable files; they are reported elsewhere.
    }
  }
  return map;
}

function pct(n: number, total: number): string {
  return total === 0 ? '0.0%' : ((n / total) * 100).toFixed(1) + '%';
}

function failedAssertionIds(run: RunResult): string[] {
  return run.assertions.filter((a) => a.status === 'fail').map((a) => a.assertionId);
}

function severityLabel(s: Severity): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/**
 * Render the red-team report. `probesPath` is the directory holding the
 * redteam scenario files (defaults to scenarios/redteam relative to the repo
 * root). `runs` is the RunResult[] to evaluate against.
 */
export function generateRedTeamReport(
  runs: RunResult[],
  probesPath: string,
  outPath: string,
): void {
  const probeIds = loadProbeIds(scenarioDir(probesPath));
  const runByScenario = new Map<string, RunResult>();
  for (const run of runs) runByScenario.set(run.scenarioId, run);

  // Order probes by probeId for determinism.
  const ordered = [...PROBES].sort((a, b) => a.probeId.localeCompare(b.probeId));

  let passed = 0;
  let failed = 0;
  let notRun = 0;
  const blockers: string[] = [];

  const rows: Array<{
    probe: Probe;
    scenarioId: string;
    status: 'pass' | 'fail' | 'not-run';
    run?: RunResult;
  }> = [];
  for (const probe of ordered) {
    let scenarioId = '';
    for (const [sid, pid] of probeIds) {
      if (pid === probe.probeId) {
        scenarioId = sid;
        break;
      }
    }
    const run = scenarioId ? runByScenario.get(scenarioId) : undefined;
    if (!run) {
      notRun += 1;
      rows.push({ probe, scenarioId, status: 'not-run' });
      continue;
    }
    const ok = run.verdict.overall === 'pass';
    if (ok) passed += 1;
    else {
      failed += 1;
      if (probe.severity === 'blocker') blockers.push(probe.probeId);
    }
    rows.push({ probe, scenarioId, status: ok ? 'pass' : 'fail', run });
  }

  const total = ordered.length;
  const lines: string[] = [];
  lines.push('# Red-team safety report');
  lines.push('');
  lines.push('> Generated by `framework/redteam/report.ts`. Offline and deterministic: no ');
  lines.push('> wall-clock timestamps, ordering by probe id. Live mode is not supported ');
  lines.push('> here; this report evaluates recorded `RunResult[]` only.');
  lines.push('');

  // ------------------------------------------------------------------ Summary
  lines.push('## Summary');
  lines.push('');
  const summary =
    `of ${String(total)} probes, ${String(passed)} pass, ${String(failed)} fail, ` +
    `${String(notRun)} not run; ` +
    `${String(blockers.length)} blocker(s) ${blockers.length ? '(' + blockers.join(', ') + ')' : 'none'}.`;
  lines.push('**' + summary + '**');
  lines.push('');
  lines.push('| metric | value |');
  lines.push('|---|---|');
  lines.push(`| total probes | ${String(total)} |`);
  lines.push(`| passed | ${String(passed)} (${pct(passed, total)}) |`);
  lines.push(`| failed | ${String(failed)} (${pct(failed, total)}) |`);
  lines.push(`| not run | ${String(notRun)} |`);
  lines.push(`| blockers | ${String(blockers.length)} |`);
  const majorCount = rows.filter((r) => r.probe.severity === 'major').length;
  const minorCount = rows.filter((r) => r.probe.severity === 'minor').length;
  lines.push(`| major | ${String(majorCount)} |`);
  lines.push(`| minor | ${String(minorCount)} |`);
  lines.push('');

  // ------------------------------------------------------------------ Severity table
  lines.push('## Severity table');
  lines.push('');
  lines.push(
    '| probe | category | severity | result | evidence (assertion ids) | evidence (trace id) | fix recommendation |',
  );
  lines.push('|---|---|---|---|---|---|---|');
  for (const row of rows) {
    const p = row.probe;
    const evidenceIds = row.run ? failedAssertionIds(row.run).join(', ') : '—';
    const traceId = row.run?.traceId || '—';
    const fix = p.fixRecommendation.replace(/\|/g, '\\|');
    lines.push(
      `| ${p.probeId} | ${p.category} | ${severityLabel(p.severity)} | ` +
        `${row.status === 'pass' ? 'PASS' : row.status === 'fail' ? 'FAIL' : 'NOT RUN'} | ` +
        `${evidenceIds} | ${traceId} | ${fix} |`,
    );
  }
  lines.push('');

  // ------------------------------------------------------------------ 60-second repro
  lines.push('## How to reproduce a blocker in 60 seconds');
  lines.push('');
  lines.push('1. Boot the app under test: `npm run app:dev` (port 4799).');
  lines.push('2. Reset the seed:');
  lines.push('   `curl -X POST http://127.0.0.1:4799/api/v1/admin/reset`');
  lines.push('3. Send the failing probe message as the scenario persona (x-actor-id header):');
  lines.push('');
  const blockerRows = rows
    .filter((r) => r.status === 'fail' && r.probe.severity === 'blocker')
    .slice(0, 3);
  if (blockerRows.length === 0) {
    lines.push('   No blocker failures in this run.');
  } else {
    for (const row of blockerRows) {
      const run = row.run;
      if (!run) continue;
      const firstUser = run.transcript.find((t) => t.role === 'user');
      const message = firstUser
        ? firstUser.content.replace(/"/g, '\\"')
        : run.finalAnswer.slice(0, 80).replace(/"/g, '\\"');
      lines.push(`   # Probe ${row.probe.probeId} — ${run.scenarioId} (${run.persona})`);
      lines.push('   curl -N -X POST http://127.0.0.1:4799/api/v1/chat \\');
      lines.push("     -H 'x-actor-id: usr_emma' -H 'Content-Type: application/json' \\");
      lines.push(
        `     -d '{ "scenarioId": "${run.scenarioId}", "messages": [{ "role": "user", "content": "${message}" }], "provider": "mock" }"'`,
      );
      lines.push(`   # Repro message: "${run.transcript[0]?.content || ''}"`);
      lines.push(`   # Failing assertions: ${failedAssertionIds(run).join(', ') || 'none'}`);
      lines.push('');
    }
  }
  lines.push(
    '4. Confirm the leaked data / write / PII appears, then apply the fix recommendation in the table above.',
  );
  lines.push('');

  // ------------------------------------------------------------------ Hardening
  lines.push('## Hardening section');
  lines.push('');
  lines.push('Every probe is designed to PASS for a correct hardened agent. The suite covers:');
  lines.push('');
  lines.push('| category | count | severity | focus |');
  lines.push('|---|---|---|---|');
  const cats: [ScenarioCategory, number][] = [
    ['injection-direct', 4],
    ['injection-indirect', 4],
    ['cross-tenant', 4],
    ['exfiltration', 3],
    ['hallucination', 3],
    ['over-action', 2],
    ['pii-in-logs', 2],
  ];
  for (const [cat, count] of cats) {
    lines.push(
      `| ${cat} | ${String(count)} | ${severityLabel(severityForCategory(cat))} | safety probe coverage |`,
    );
  }
  lines.push('');
  lines.push(
    'Fairness rule: every probe passes for a hardened agent. Probes that fail in the default run name',
  );
  lines.push(
    'the latent bug surface in their scenario rationale (scn-core-008 partial write, scn-core-019 stale role,',
  );
  lines.push(
    'scn-core-024 unlogged span, scn-core-030 hallucination). Every probe is a real, runnable safety check.',
  );
  lines.push('');

  lines.push('## Probe catalogue (source of truth)');
  lines.push('');
  lines.push('| probe | category | severity | title |');
  lines.push('|---|---|---|---|');
  for (const p of ordered) {
    lines.push(
      `| ${p.probeId} | ${p.category} | ${severityLabel(p.severity)} | ${p.title.replace(/\|/g, '\\|')} |`,
    );
  }
  lines.push('');

  const outDir = dirname(outPath);
  if (outDir) mkdirSync(outDir, { recursive: true });
  writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
}

export { severityForCategory, severityRank };
export type { Probe };
